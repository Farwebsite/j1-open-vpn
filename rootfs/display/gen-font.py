"""Renders the screen fonts and icons into j1-ui-font.h (antialiased 8-bit
alpha masks), so j1-display needs no font library on the J1. Only needed when
the fonts, sizes or icons change; the generated header is in the repository.
Fonts: Inter (SIL OFL 1.1) and Material Icons (Apache 2.0), in fonts/.
usage: python3 gen-font.py   (needs Pillow and fontTools)"""
import pathlib
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

HERE = pathlib.Path(__file__).resolve().parent
FONTS = HERE / 'fonts'
# web.py sends cp437; the low control codes are the arrows the keyboard uses
CP437 = {b: bytes([b]).decode('cp437') for b in range(0x20, 0x100)}
CP437.update({0x18: '↑', 0x19: '↓', 0x1a: '→', 0x1b: '←'})
# name, file, pixel size, characters (None = all of cp437)
TEXT = (('f_sm', 'Inter-Regular.ttf', 18, None),     # small print
        ('f_md', 'Inter-Medium.ttf', 23, None),      # normal text, buttons
        ('f_tt', 'Inter-SemiBold.ttf', 25, None),    # title bar
        ('f_st', 'Inter-SemiBold.ttf', 17, None),    # clock and battery in the bar
        ('f_xl', 'Inter-Light.ttf', 112, '0123456789:'))   # lock screen clock
# screen name -> Material Icons name
ICONS = (('wifi', 'wifi'), ('ap', 'wifi_tethering'), ('vpn', 'verified_user'), ('dns', 'cloud'),
         ('usb', 'settings_ethernet'), ('res', 'insights'), ('disp', 'light_mode'), ('logs', 'article'),
         ('sys', 'settings'), ('qr', 'qr_code_2'), ('ip', 'lan'), ('user', 'person'),
         ('power', 'power_settings_new'), ('speed', 'speed'), ('tz', 'schedule'), ('lock', 'lock'), ('panel', 'language'),
         ('more', 'chevron_right'), ('back', 'arrow_back_ios_new'))
ICON_SIZES = (30, 46)

def arr(data):
    return ','.join(map(str, data))

def font(name, file, size, chars, out):
    f = ImageFont.truetype(str(FONTS / file), size)
    cmap = TTFont(str(FONTS / file))['cmap'].getBestCmap()
    glyphs, alpha = [], []
    for b in range(256):
        ch = CP437.get(b)
        if ch is None or (chars and ch not in chars) or (ord(ch) not in cmap and ch != ' '):
            glyphs.append((0, 0, 0, 0, 0, 0)); continue
        adv = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch, anchor='ls')
        w, h = max(x1 - x0, 0), max(y1 - y0, 0)
        if not w or not h:
            glyphs.append((adv, 0, 0, 0, 0, 0)); continue
        im = Image.new('L', (w, h)); ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
        glyphs.append((adv, x0, y0, w, h, len(alpha))); alpha += list(im.tobytes())
    asc, desc = f.getmetrics()
    out.append('static const uint8_t %s_a[] = {%s};' % (name, arr(alpha or [0])))
    out.append('static const struct glyph %s_g[256] = {%s};' % (name, ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs)))
    out.append('static const struct font %s = {%d, %d, %d, %s_g, %s_a};' % (name, size, asc, desc, name, name))
    return len(alpha)

def icons(out):
    f = {s: ImageFont.truetype(str(FONTS / 'MaterialIcons-Regular.ttf'), s) for s in ICON_SIZES}
    points = dict(l.split() for l in (FONTS / 'MaterialIcons-Regular.codepoints').read_text().splitlines())
    rows = []
    for short, long in ICONS:
        ch = chr(int(points[long], 16))
        for s in ICON_SIZES:
            im = Image.new('L', (s, s)); ImageDraw.Draw(im).text((s // 2, s // 2), ch, font=f[s], fill=255, anchor='mm')
            out.append('static const uint8_t icon_%s_%d[] = {%s};' % (short, s, arr(im.tobytes())))
        rows.append('{"%s", {%s}}' % (short, ', '.join('icon_%s_%d' % (short, s) for s in ICON_SIZES)))
    out.append('#define ICON_SIZES {%s}' % ', '.join(map(str, ICON_SIZES)))
    out.append('static const struct icon_def { const char *name; const uint8_t *a[%d]; } ICON_DEFS[] = {%s};' % (len(ICON_SIZES), ', '.join(rows)))

out = ['/* generated by gen-font.py from Inter (SIL OFL 1.1, fonts/Inter-LICENSE.txt) and',
       ' * Material Icons (Apache 2.0, fonts/MaterialIcons-LICENSE.txt); do not edit */',
       '#include <stdint.h>',
       '/* glyph: advance, left bearing, top relative to the baseline, size, offset in the alpha mask */',
       'struct glyph { int16_t adv, ox, oy, w, h; int32_t off; };',
       'struct font { int size, asc, desc; const struct glyph *g; const uint8_t *a; };']
total = sum(font(*t, out) for t in TEXT)
icons(out)
(HERE / 'j1-ui-font.h').write_text('\n'.join(out) + '\n', newline='\n')

# the web panel uses the same icons, as inline SVG paths in web.py (between markers)
WEB_ICONS = (('wifi', 'wifi'), ('cable', 'settings_ethernet'), ('vpn', 'verified_user'), ('dns', 'cloud'),
             ('key', 'key'), ('ap', 'wifi_tethering'), ('lock', 'lock'), ('tz', 'schedule'), ('ssh', 'terminal'),
             ('download', 'download'), ('user', 'person'))
def web_icons():
    from fontTools.pens.svgPathPen import SVGPathPen
    f = TTFont(str(FONTS / 'MaterialIcons-Regular.ttf'))
    gs, cmap = f.getGlyphSet(), f.getBestCmap()
    points = dict(l.split() for l in (FONTS / 'MaterialIcons-Regular.codepoints').read_text().splitlines())
    rows = []
    for short, long in WEB_ICONS:
        pen = SVGPathPen(gs, ntos=lambda v: ('%d' % v) if v == int(v) else ('%.1f' % v))
        gs[cmap[int(points[long], 16)]].draw(pen)
        rows.append("    '%s':'%s'," % (short, pen.getCommands()))
    web = HERE.parent / 'overlay/usr/local/lib/j1/web.py'
    s = web.read_text(encoding='utf8')
    a, b = s.index('# ---- icons: generated'), s.index('# ---- end of icons')
    block = ('# ---- icons: generated by rootfs/display/gen-font.py from Material Icons (Apache 2.0)\n'
             'ICONS_SVG={\n' + '\n'.join(rows) + '\n}\n')
    web.write_text(s[:a] + block + s[b:], encoding='utf8', newline='\n')
    print('web.py: %d icons' % len(rows))
web_icons()
print('j1-ui-font.h: %d bytes of glyphs' % total)
